"""Build the Phase 4 training rows from the synthetic train and dev splits.

    python scripts/phase4_prepare.py

Writes data/phase4/{train,dev}.jsonl (not committed; regenerated byte for byte)
and data/phase4/manifest.json with their SHA-256 hashes. Every row carries the
frozen E1 prompt and the SymPy checker's first wrong step, which is asserted to
match the generator label.
"""
import hashlib
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from core.phase2 import load_synthetic  # noqa: E402
from core.phase4 import DATA, SPLITS, TARGET_VERSION, prepare  # noqa: E402
from core.prompts import PROMPT_VERSION  # noqa: E402


def main():
    DATA.mkdir(parents=True, exist_ok=True)
    manifest = {"target_version": TARGET_VERSION, "prompt_version": PROMPT_VERSION, "splits": {}}
    for split in SPLITS:
        rows = [prepare(item) for item in load_synthetic(split)]
        path = DATA / f"{split}.jsonl"
        with path.open("w", encoding="utf-8", newline="\n") as f:
            for r in rows:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        steps = Counter(r["checker_step"] for r in rows)
        manifest["splits"][split] = {"n": len(rows), "checker_step_counts": dict(sorted(steps.items())),
                                     "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
        print(split, len(rows), dict(sorted(steps.items())))
    (DATA / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
